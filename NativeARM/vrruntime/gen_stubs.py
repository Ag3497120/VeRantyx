#!/usr/bin/env python3
"""Generate gen_stubs.h: for every OpenVR interface the runtime may be asked
for, a Stub_<Interface> class that implements every method with a logged,
default-valued body. The real implementations derive from these and override
only what the game needs, so a method nobody expected to be called is reported
by name instead of faulting.

    python3 gen_stubs.py            # writes gen_stubs.h next to this file
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCES = ["openvr/openvr.h", "openvr/ivrclientcore.h", "openvr/ivrapplications_007.h"]
CLASSES = [
    "IVRSystem", "IVRCompositor", "IVRInput", "IVRChaperone", "IVRChaperoneSetup",
    "IVROverlay", "IVROverlayView", "IVRRenderModels", "IVRApplications",
    "IVRApplications_007", "IVRHeadsetView", "IVRSettings", "IVRScreenshots",
    "IVRResources", "IVRExtendedDisplay", "IVRTrackedCamera", "IVRNotifications",
    "IVRDriverManager", "IVRDebug", "IVRIOBuffer", "IVRSpatialAnchors",
    "IVRClientCore", "IVRIPCResourceManagerClient",
]


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def class_body(text, name):
    m = re.search(r"\bclass\s+%s\s*\{" % re.escape(name), text)
    if not m:
        return None
    depth, i = 0, m.end() - 1
    while i < len(text):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[m.end():i]
        i += 1
    return None


def methods(body):
    out = []
    for stmt in body.split(";"):
        stmt = " ".join(stmt.split())
        stmt = re.sub(r"^(public|private|protected):\s*", "", stmt)
        if not stmt.startswith("virtual "):
            continue
        stmt = stmt[len("virtual "):]
        if stmt.startswith("~"):
            continue          # virtual destructor
        stmt = re.sub(r"\s*=\s*0\s*$", "", stmt)
        const = ""
        if stmt.endswith(" const"):
            stmt, const = stmt[:-6], " const"
        m = re.match(r"(.+?)\b(\w+)\s*\((.*)\)\s*$", stmt)
        if not m:
            raise SystemExit("cannot parse: " + stmt)
        ret, name, params = m.group(1).strip(), m.group(2), m.group(3).strip()
        # Default arguments must not be repeated on an override.
        plist = []
        for p in split_params(params):
            p = re.sub(r"\s*=\s*[^,]+$", "", p).strip()
            plist.append(p)
        out.append((ret, name, plist, const))
    return out


def split_params(s):
    if not s or s == "void":
        return []
    parts, depth, cur = [], 0, ""
    for ch in s:
        if ch in "(<[":
            depth += 1
        elif ch in ")>]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return [p.strip() for p in parts if p.strip()]


def param_name(p):
    # "const char *pchName" -> pchName ; "uint32_t unSize" -> unSize ; arrays "float x[3]"
    p = re.sub(r"\[.*\]$", "", p)
    m = re.search(r"(\w+)\s*$", p)
    return m.group(1) if m else None


def main():
    text = ""
    for s in SOURCES:
        text += strip_comments(open(os.path.join(HERE, s)).read()) + "\n"
    out = ["// GENERATED by gen_stubs.py from the OpenVR headers — do not edit.",
           "#pragma once", '#include "openvr/openvr.h"', '#include "openvr/ivrclientcore.h"',
           '#include "openvr/ivrapplications_007.h"', "#include <cstdio>", "using namespace vr;",
           "", "void vrrt_log_unimplemented(const char *iface, const char *method);", ""]
    for cls in CLASSES:
        body = class_body(text, cls)
        if body is None:
            print("missing class", cls)
            continue
        ms = methods(body)
        out.append("class Stub_%s : public vr::%s {" % (cls, cls))
        out.append("public:")
        for ret, name, params, const in ms:
            sig = ", ".join(params)
            if ret.strip() == "void":
                body_s = 'vrrt_log_unimplemented("%s", "%s");' % (cls, name)
            elif "*" in ret:
                body_s = 'vrrt_log_unimplemented("%s", "%s"); return nullptr;' % (cls, name)
            else:
                body_s = 'vrrt_log_unimplemented("%s", "%s"); return %s{};' % (cls, name, ret.strip())
            out.append("    %s %s(%s)%s override { %s }" % (ret, name, sig, const, body_s))
        out.append("};")
        out.append("")
        print("%-28s %3d methods" % (cls, len(ms)))
    open(os.path.join(HERE, "gen_stubs.h"), "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
