// Writes cpuid_table.h from what Rosetta 2 reports (built for x86-64; run as
// `ROSETTA_ADVERTISE_AVX=1 arch -x86_64 cpuid_dump > cpuid_table.h`), with the rate its TSC counts at.
#include <cpuid.h>
#include <stdint.h>
#include <stdio.h>
#include <time.h>
#include <x86intrin.h>
static void leaf(uint32_t l, uint32_t s, int any) {
    uint32_t a, b, c, d; __cpuid_count(l, s, a, b, c, d);
    printf("    { 0x%08x, 0x%08x, { 0x%08x, 0x%08x, 0x%08x, 0x%08x } },\n", l, any ? 0xFFFFFFFFu : s, a, b, c, d);
}
int main(void) {
    printf("// Generated by tools/cpuid_dump.c from Rosetta 2 (ROSETTA_ADVERTISE_AVX=1): leaf, subleaf (all: ~0), EAX EBX ECX EDX.\n");
    printf("static const struct { uint32_t leaf, sub, r[4]; } cpuid_table[] = {\n");
    uint32_t a, b, c, d; __cpuid(0, a, b, c, d);
    for (uint32_t l = 0; l <= a; l++) {
        if (l == 4 || l == 7 || l == 0xB || l == 0xD || l == 0xF || l == 0x10 || l == 0x12 || l == 0x14 || l == 0x17 || l == 0x18) for (uint32_t s = 0; s < 8; s++) leaf(l, s, 0);
        else leaf(l, 0, 1);
    }
    __cpuid(0x80000000, a, b, c, d);
    for (uint32_t l = 0x80000000; l <= a; l++) leaf(l, 0, 1);
    printf("};\n");
    struct timespec t0, t1; clock_gettime(CLOCK_MONOTONIC, &t0); uint64_t r0 = __rdtsc();
    do clock_gettime(CLOCK_MONOTONIC, &t1); while ((t1.tv_sec - t0.tv_sec) * 1000000000L + (t1.tv_nsec - t0.tv_nsec) < 500000000L);
    uint64_t r1 = __rdtsc();
    double hz = (double)(r1 - r0) / ((t1.tv_sec - t0.tv_sec) + (t1.tv_nsec - t0.tv_nsec) * 1e-9);
    printf("#define CPUID_TSC_HZ %lluull   // (measured: %.0f)\n", (unsigned long long)((hz + 500000) / 1000000) * 1000000ull, hz);
    return 0;
}
