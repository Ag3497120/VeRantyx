DWORD vx_ntstatus_to_win32(uint32_t status) {
    if (!status) return 0;
    if ((status & 0xffff0000u) == 0xc0070000u) return status & 0xffff;     // a Win32 error carried as a status (FACILITY_NTWIN32)
    size_t lo = 0, hi = sizeof g_status_errors / sizeof g_status_errors[0];
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (g_status_errors[mid].status < status) lo = mid + 1; else hi = mid;
    }
    if (lo < sizeof g_status_errors / sizeof g_status_errors[0] && g_status_errors[lo].status == status) return g_status_errors[lo].error;
    return 317;                                                             // ERROR_MR_MID_NOT_FOUND: no Win32 code for it
}

// The status a Win32 error comes from in the usual case (several statuses share most errors: this is the one a failed
// file, memory or object call reports); any other error goes back as the Win32 error carried in a status.
