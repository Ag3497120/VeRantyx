#!/usr/bin/env python3
"""Generates src/gl_thunks.h: for every OpenGL function in the macOS SDK's headers (legacy gl.h/glext.h and core
gl3.h), a pointer looked up in OpenGL.framework at run time and a Windows-calling-convention function that calls it,
plus a name table. Windows programs get these from opengl32.dll (src/opengl.c). Without a current context a call does
nothing (and returns 0), as on Windows.

    tools/gen_gl_thunks.py > src/gl_thunks.h
"""
import re, subprocess, sys
sdk = subprocess.check_output(["xcrun", "--show-sdk-path"], text=True).strip()
hdr = sdk + "/System/Library/Frameworks/OpenGL.framework/Headers/"
funcs = {}
def add(ret, name, args):
    args = re.sub(r"\s+", " ", args).strip()
    if name in funcs: return
    if "PROC" in args or "Proc" in args or "CALLBACK" in args: return    # callbacks would be called with the wrong convention
    funcs[name] = (ret.strip(), args)
for f in ("gl.h", "glext.h"):
    text = open(hdr + f).read()
    for m in re.finditer(r"extern\s+([\w\s\*]+?)\s*\b(gl[A-Z]\w*)\s*\(([^)]*)\)", text):
        add(m.group(1), m.group(2), m.group(3))
text = open(hdr + "gl3.h").read()
for m in re.finditer(r"GLAPI\s+([\w\s\*]+?)\s+APIENTRY\s+(gl[A-Z]\w*)\s*\(([^)]*)\)", text):
    add(m.group(1), m.group(2), m.group(3))
def split(args):
    if args in ("", "void"): return [], []
    types, names = [], []
    for i, a in enumerate(args.split(",")):
        a = a.strip()
        m = re.match(r"(.*?)(\w+)\s*((\[\d*\])*)$", a)
        if not m or m.group(1).strip() in ("", "const"): t, n = a, "a%d" % i
        else:
            t, n = m.group(1).strip(), m.group(2)
            if m.group(3): t += " *"
        types.append(t); names.append("p_" + n)
    return types, names
out = ["// Generated by tools/gen_gl_thunks.py from the macOS SDK's OpenGL headers: do not edit.",
       "// %d functions." % len(funcs)]
table = []
for name in sorted(funcs):
    ret, args = funcs[name]
    types, names = split(args)
    params = ", ".join("%s %s" % (t, n) for t, n in zip(types, names)) or "void"
    out.append("typedef %s (*fp_%s)(%s);" % (ret, name, ", ".join(types) or "void"))
    out.append("static fp_%s r_%s;" % (name, name))
    call = "r_%s(%s)" % (name, ", ".join(names))
    # Without a current context macOS's GL functions crash (Windows' do nothing): nothing then.
    guard = "if (!CGLGetCurrentContext()) return%s; " % ("" if ret == "void" else " (%s)0" % ret)
    out.append("static WINAPI %s w_%s(%s) { %s%s%s; }" % (ret, name, params, guard, "" if ret == "void" else "return ", call))
    table.append('    { "%s", (void *)w_%s, (void **)&r_%s },' % (name, name, name))
out.append("static const struct { const char *name; void *thunk; void **real; } g_gl_functions[] = {")
out += table
out.append("};")
print("\n".join(out))
