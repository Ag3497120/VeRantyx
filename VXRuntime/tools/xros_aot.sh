#!/bin/sh
# xros_aot.sh <pe>...: route-B modules for the visionOS app (VISIONOS_PORT.md). Each image's modules are assembled for
# the device and linked into the app, since an app there may load no code made after it was signed: each module's
# descriptor gets a name of its own (vxrt_aot_module_<n>), and build/xros/aot/registry.c lists them under the file
# names translator/aot.c asks for (<name>-<hash>[.p<k>].dylib). Output: build/$XROS_SDK/libaot.a (xros or xrsimulator).
# Only for our own test programs: a game's translated code is never put in an app here (RECOMP.md).
set -e
cd "$(dirname "$0")/.."
SDK=${XROS_SDK:-xros}
CC="xcrun -sdk $SDK clang -target ${XROS_TARGET:-arm64-apple-xros26.0}"
out=build/$SDK/aot
rm -rf "$out"; mkdir -p "$out"
reg=$out/registry.c
printf '// generated by tools/xros_aot.sh\n#include "../../../translator/aot.h"\n' > "$reg"
entries=""
i=0
for pe in "$@"; do
    name=$(build/vxrt-aot name "$pe"); stem=${name%.dylib}
    b=$(basename "$pe")
    build/vxrt-aot gen "$pe" "$out/$b.s" > "$out/$b.list"
    while read -r f; do
        case "$f" in *.p[0-9]*.s) k=${f##*.p}; k=${k%.s}; mod="$stem.p$k.dylib" ;; *) mod="$stem.dylib" ;; esac
        sed "s/_vxrt_aot_module\$/_vxrt_aot_module_$i/; s/_vxrt_aot_module:/_vxrt_aot_module_$i:/" "$f" > "$out/m$i.s"
        $CC -c -o "$out/m$i.o" "$out/m$i.s"
        printf 'extern const xa_desc vxrt_aot_module_%d;\n' $i >> "$reg"
        entries="$entries    { \"$mod\", &vxrt_aot_module_$i },\n"
        i=$((i + 1))
    done < "$out/$b.list"
done
printf 'typedef struct { const char *name; const xa_desc *desc; } xa_static;\nconst xa_static vxrt_aot_static[] = {\n%b    { 0, 0 }\n};\n' "$entries" >> "$reg"
$CC -c -O1 -o "$out/registry.o" "$reg"
rm -f build/$SDK/libaot.a
xcrun -sdk $SDK libtool -static -o build/$SDK/libaot.a "$out"/m*.o "$out/registry.o"
echo "xros_aot: $i modules for $# images -> build/$SDK/libaot.a"
