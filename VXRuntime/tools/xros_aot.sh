#!/bin/sh
# xros_aot.sh [fw:]<pe>[@<hex base>]...: route-B modules for the visionOS app (VISIONOS_PORT.md). An app there may load
# no code made after it was signed, so each module is either
#   - linked into the app (the default): its descriptor gets a name of its own (vxrt_aot_module_<n>) and
#     build/$XROS_SDK/aot/registry.c lists it under the file name translator/aot.c asks for (<name>-<hash>[.p<k>].dylib),
#     all of them in build/$XROS_SDK/libaot.a; or
#   - with "fw:", a framework of its own, build/$XROS_SDK/aot_fw/VXA_<file name>.framework, which the app's build
#     embeds and signs (xros/app/embed_aot_frameworks.sh) and aot.c opens with dlopen (large modules: a game's).
# "@<hex base>": the image as loaded there (VXRT_AOT_BASE), for an image in the arena. The arena the modules are
# made for is XROS_ARENA (hex) and XROS_ARENA_MB; the registry carries both, and the app reserves that range first.
# Only for our own test programs: a game's translated code is never put in an app here (RECOMP.md).
set -e
cd "$(dirname "$0")/.."
SDK=${XROS_SDK:-xros}
TARGET=${XROS_TARGET:-arm64-apple-xros26.0}
CC="xcrun -sdk $SDK clang -target $TARGET"
ARENA=${XROS_ARENA:-0xf00000000}
ARENA_MB=${XROS_ARENA_MB:-512}
out=build/$SDK/aot
fwout=build/$SDK/aot_fw
rm -rf "$out" "$fwout"; mkdir -p "$out" "$fwout"
reg=$out/registry.c
printf '// generated by tools/xros_aot.sh\n#include "../../../translator/aot.h"\n' > "$reg"
printf 'const uint64_t vxrt_aot_arena_base = %s, vxrt_aot_arena_size = %sull << 20;\n' "$ARENA" "$ARENA_MB" >> "$reg"
entries=""
i=0; nfw=0
for arg in "$@"; do
    fw=0; case "$arg" in fw:*) fw=1; arg=${arg#fw:} ;; esac
    pe=${arg%@*}; base=""; [ "$pe" != "$arg" ] && base=${arg##*@}
    name=$(build/vxrt-aot name "$pe"); stem=${name%.dylib}
    b=$(basename "$pe")
    if [ -n "$base" ]; then VXRT_AOT_BASE=${base#0x} build/vxrt-aot gen "$pe" "$out/$b.s" > "$out/$b.list"
    else build/vxrt-aot gen "$pe" "$out/$b.s" > "$out/$b.list"; fi
    while read -r f; do
        case "$f" in *.p[0-9]*.s) k=${f##*.p}; k=${k%.s}; mod="$stem.p$k.dylib" ;; *) mod="$stem.dylib" ;; esac
        if [ $fw = 1 ]; then
            # (the framework's name: the module's file name, lowercased, other characters '_' (aot.c's fw_path))
            fwn=VXA_$(printf '%s' "${mod%.dylib}" | tr 'A-Z' 'a-z' | tr -c 'a-z0-9\n' '_')
            d=$fwout/$fwn.framework; mkdir -p "$d"
            $CC -c -o "$out/f$nfw.o" "$f"
            $CC -dynamiclib -install_name "@rpath/$fwn.framework/$fwn" -o "$d/$fwn" "$out/f$nfw.o"
            id=marimokodai.VXRuntimeHost.aot.$(printf '%s' "$fwn" | tr '_' '-')
            cat > "$d/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>CFBundleExecutable</key><string>$fwn</string>
<key>CFBundleIdentifier</key><string>$id</string>
<key>CFBundleName</key><string>$fwn</string>
<key>CFBundlePackageType</key><string>FMWK</string>
<key>CFBundleShortVersionString</key><string>1.0</string>
<key>CFBundleVersion</key><string>1</string>
<key>CFBundleSupportedPlatforms</key><array><string>$( [ "$SDK" = xros ] && echo XROS || echo XRSimulator )</string></array>
<key>MinimumOSVersion</key><string>26.0</string>
</dict></plist>
EOF
            rm -f "$out/f$nfw.o"
            nfw=$((nfw + 1))
        else
            sed "s/_vxrt_aot_module\$/_vxrt_aot_module_$i/; s/_vxrt_aot_module:/_vxrt_aot_module_$i:/" "$f" > "$out/m$i.s"
            $CC -c -o "$out/m$i.o" "$out/m$i.s"
            printf 'extern const xa_desc vxrt_aot_module_%d;\n' $i >> "$reg"
            entries="$entries    { \"$mod\", &vxrt_aot_module_$i },\n"
            i=$((i + 1))
        fi
    done < "$out/$b.list"
done
printf 'typedef struct { const char *name; const xa_desc *desc; } xa_static;\nconst xa_static vxrt_aot_static[] = {\n%b    { 0, 0 }\n};\n' "$entries" >> "$reg"
$CC -c -O1 -o "$out/registry.o" "$reg"
rm -f build/$SDK/libaot.a
objs="$out/registry.o"; [ $i -gt 0 ] && objs="$out/m*.o $objs"
xcrun -sdk $SDK libtool -static -o build/$SDK/libaot.a $objs
echo "xros_aot: $i modules linked, $nfw frameworks, for $# images (arena $ARENA, $ARENA_MB MB) -> build/$SDK/libaot.a, $fwout"
