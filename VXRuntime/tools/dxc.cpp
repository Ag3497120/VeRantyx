// Compiles HLSL to DXIL (Shader Model 6) with Microsoft's dxcompiler.dll (for example the one Chromium ships beside
// SteamVR's vrwebhelper), running on VXRuntime itself, and writes the container as raw bytes and as a C array:
//   vxrt build/dxc.exe <dxcompiler.dll> <file.hlsl> <entry> <profile> <out.h> <array name>
// (out.h -> out.dxil beside it, the raw container, for tools that read DXIL.)
//   vxrt build/dxc.exe -dis <dxcompiler.dll> <file.dxil> <out.txt>
// DXC's own disassembly of a container: the reference src/dxil.c's reading is checked against.
#include <windows.h>
#include <dxcapi.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <wchar.h>

static wchar_t *wide(const char *s) {
    int n = MultiByteToWideChar(CP_UTF8, 0, s, -1, NULL, 0);
    wchar_t *w = (wchar_t *)malloc(n * sizeof(wchar_t));
    MultiByteToWideChar(CP_UTF8, 0, s, -1, w, n);
    return w;
}

static int disassemble(const char *dllpath, const char *in, const char *outpath) {
    HMODULE dll = LoadLibraryA(dllpath);
    DxcCreateInstanceProc create = dll ? (DxcCreateInstanceProc)GetProcAddress(dll, "DxcCreateInstance") : NULL;
    if (!create) { printf("cannot load DxcCreateInstance from %s\n", dllpath); return 1; }
    IDxcCompiler3 *compiler = NULL;
    if (FAILED(create(CLSID_DxcCompiler, __uuidof(IDxcCompiler3), (void **)&compiler))) return 1;
    FILE *f = fopen(in, "rb");
    if (!f) { printf("cannot open %s\n", in); return 1; }
    char *data = (char *)malloc(1 << 22);
    size_t n = fread(data, 1, 1 << 22, f);
    fclose(f);
    DxcBuffer buffer = { data, n, 0 };
    IDxcResult *result = NULL;
    if (FAILED(compiler->Disassemble(&buffer, __uuidof(IDxcResult), (void **)&result))) { printf("Disassemble failed\n"); return 1; }
    IDxcBlobUtf8 *text = NULL;
    result->GetOutput(DXC_OUT_DISASSEMBLY, __uuidof(IDxcBlobUtf8), (void **)&text, NULL);
    if (!text) { printf("no disassembly\n"); return 1; }
    FILE *out = fopen(outpath, "wb");
    fwrite(text->GetStringPointer(), 1, text->GetStringLength(), out);
    fclose(out);
    printf("%s: %zu bytes\n", outpath, (size_t)text->GetStringLength());
    return 0;
}

int main(int argc, char **argv) {
    if (argc == 5 && !strcmp(argv[1], "-dis")) return disassemble(argv[2], argv[3], argv[4]);
    if (argc != 7) { printf("usage: dxc <dxcompiler.dll> <file.hlsl> <entry> <profile> <out.h> <name>\n"); return 2; }
    HMODULE dll = LoadLibraryA(argv[1]);
    DxcCreateInstanceProc create = dll ? (DxcCreateInstanceProc)GetProcAddress(dll, "DxcCreateInstance") : NULL;
    if (!create) { printf("cannot load DxcCreateInstance from %s (error %lu)\n", argv[1], GetLastError()); return 1; }
    IDxcCompiler3 *compiler = NULL;
    HRESULT hr = create(CLSID_DxcCompiler, __uuidof(IDxcCompiler3), (void **)&compiler);
    if (FAILED(hr)) { printf("DxcCreateInstance: %#lx\n", hr); return 1; }
    FILE *f = fopen(argv[2], "rb");
    if (!f) { printf("cannot open %s\n", argv[2]); return 1; }
    char *src = (char *)malloc(1 << 20);
    size_t n = fread(src, 1, (1 << 20) - 1, f);
    fclose(f);
    DxcBuffer buffer = { src, n, DXC_CP_UTF8 };
    // (no debug information, no reflection in the container: what a game's shipped shaders look like)
    // A profile ending in "+16" (cs_6_2+16) compiles with native 16-bit types (-enable-16bit-types).
    char profile[32];
    snprintf(profile, sizeof profile, "%s", argv[4]);
    char *plus = strstr(profile, "+16");
    if (plus) *plus = 0;
    const wchar_t *args[] = { wide(argv[2]), L"-E", wide(argv[3]), L"-T", wide(profile), L"-Qstrip_debug", L"-Qstrip_reflect", L"-O3",
                              L"-enable-16bit-types" };
    IDxcResult *result = NULL;
    hr = compiler->Compile(&buffer, args, sizeof args / sizeof *args - (plus ? 0 : 1), NULL, __uuidof(IDxcResult), (void **)&result);
    if (FAILED(hr)) { printf("Compile: %#lx\n", hr); return 1; }
    IDxcBlobUtf8 *errors = NULL;
    result->GetOutput(DXC_OUT_ERRORS, __uuidof(IDxcBlobUtf8), (void **)&errors, NULL);
    if (errors && errors->GetStringLength()) printf("%s", errors->GetStringPointer());
    HRESULT status = E_FAIL;
    result->GetStatus(&status);
    IDxcBlob *code = NULL;
    result->GetOutput(DXC_OUT_OBJECT, __uuidof(IDxcBlob), (void **)&code, NULL);
    if (FAILED(status) || !code || !code->GetBufferSize()) { printf("compilation failed: %#lx\n", status); return 1; }
    const unsigned char *p = (const unsigned char *)code->GetBufferPointer();
    size_t size = code->GetBufferSize();
    FILE *out = fopen(argv[5], "w");
    fprintf(out, "// %s, %s %s: DXIL compiled from %s. Generated by tools/dxc.cpp.\n", argv[6], argv[3], argv[4], argv[2]);
    fprintf(out, "static const unsigned char %s[%zu] = {", argv[6], size);
    for (size_t i = 0; i < size; i++) fprintf(out, "%s0x%02x,", i % 16 ? " " : "\n    ", p[i]);
    fprintf(out, "\n};\n");
    fclose(out);
    char raw[MAX_PATH];
    snprintf(raw, sizeof raw, "%.*s.dxil", (int)(strlen(argv[5]) > 2 ? strlen(argv[5]) - 2 : strlen(argv[5])), argv[5]);
    FILE *rf = fopen(raw, "wb");
    if (rf) { fwrite(p, 1, size, rf); fclose(rf); }
    printf("%s: %zu bytes\n", argv[5], size);
    return 0;
}
