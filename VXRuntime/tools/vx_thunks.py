#!/usr/bin/env python3
"""Thunks for the ARM64 build (generated C, no machine code): for every function with the Windows calling convention
in a source file (tools/vx_abi_scan.py), one `static void vxt_<name>(x86_ctx *)` that reads the arguments where
translated x86 code left them (RCX RDX R8 R9 / XMM0-3, then the stack), calls the function and puts its result in
RAX or XMM0; and a table of them, registered by address (src/arm64.c), so that the engine turns a call to the
function into a call of its thunk. Written to <out>/<file>.inc, included at the end of the file in the ARM64 build.

It also checks the other direction: every call through an ms_abi function pointer (the runtime calling what may be
x86 code) must pass and return integers or pointers only, as the ARM64 build's callback bridge moves x0-x7 to
RCX RDX R8 R9 and the stack; one that does not is an error here.

usage: vx_thunks.py <out dir> <source.c|.m> ..."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vx_abi_scan as scan

# canonical CXType kind -> the integer type an argument is cut to first (x64 leaves the bits above a narrow
# argument undefined)
WIDTH = {3: "uint8_t", 4: "uint8_t", 5: "uint8_t", 6: "uint16_t", 7: "uint32_t", 8: "uint16_t", 9: "uint32_t",
         10: "uint64_t", 11: "uint64_t", 13: "int8_t", 14: "int8_t", 15: "int32_t", 16: "int16_t", 17: "int32_t",
         18: "int64_t", 19: "int64_t"}
SIZED = {1: "uint8_t", 2: "uint16_t", 4: "uint32_t", 8: "uint64_t"}

def width(kind, size):
    if kind in WIDTH: return WIDTH[kind]
    if kind == 106: return SIZED.get(size, "uint64_t")          # enum
    return "uintptr_t"                                          # pointers (and arrays, as parameters)

def arg(p, i):
    if p["cls"] == "float": return f"vx_arg_f(c, {i})"
    if p["cls"] == "double": return f"vx_arg_d(c, {i})"
    if p["cls"] == "rec8": return f"({{ {p['type']} v_; uint64_t s_ = vx_arg(c, {i}); memcpy(&v_, &s_, sizeof v_); v_; }})"
    if p["kind"] in (112, 114): return f"(void *)(uintptr_t)vx_arg(c, {i})"
    if p["cls"] != "int": raise SystemExit(f"cannot pass {p}")
    return f"({p['type']})({width(p['kind'], p['size'])})vx_arg(c, {i})"

def thunk(f):
    n = len(f["params"])
    args = ", ".join(arg(p, i) for i, p in enumerate(f["params"]))
    call = f"{f['name']}({args})"
    pre = f"vx_va_begin(c, {n}); " if f["variadic"] else ""
    rc = f["ret_cls"]
    if rc == "void": body = f"{call};"
    elif rc == "float": body = f"vx_ret_f(c, {call});"
    elif rc == "double": body = f"vx_ret_d(c, {call});"
    elif rc == "rec8": body = f"{f['ret']} r_ = {call}; c->gpr[0] = 0; memcpy(&c->gpr[0], &r_, sizeof r_);"
    elif rc == "int": body = f"c->gpr[0] = (uint64_t)({width(f['ret_kind'], f['ret_size'])})({call});"
    else: raise SystemExit(f"cannot return {f}")
    return f"static void vxt_{f['name']}(x86_ctx *c) {{ {pre}{body} }}"

def main():
    out, srcs = sys.argv[1], sys.argv[2:]
    os.makedirs(out, exist_ok=True)
    index = scan.createIndex(0, 0)
    bad = []
    for src in srcs:
        r = scan.scan(src, index)
        for cb in r["callbacks"]:
            if cb["ret_cls"] not in ("int", "void") or any(p != "int" for p in cb["params"]):
                bad.append(f"{src}:{cb['line']}: a call through an ms_abi pointer with {cb['ret_cls']}({', '.join(cb['params'])})")
        base = os.path.basename(src).replace(".", "_")
        lines = [f"// Generated by tools/vx_thunks.py from {src}: thunks for translated x86 code (ARM64 build). Do not edit.",
                 '#include "arm64.h"']
        lines += [thunk(f) for f in r["functions"]]
        lines.append(f"static const vx_thunk vx_thunks_{base}[] = {{")
        lines += [f"    {{ (const void *){f['name']}, vxt_{f['name']} }}," for f in r["functions"]]
        lines.append("    { 0, 0 }")
        lines.append("};")
        lines.append(f"__attribute__((constructor)) static void vx_thunks_{base}_add(void) {{ vx_thunks_add(vx_thunks_{base}, sizeof vx_thunks_{base} / sizeof *vx_thunks_{base} - 1); }}")
        path = os.path.join(out, os.path.basename(src) + ".inc")
        text = "\n".join(lines) + "\n"
        if not os.path.exists(path) or open(path).read() != text: open(path, "w").write(text)
    if bad:
        print("\n".join(bad), file=sys.stderr)
        print("vx_thunks: the ARM64 callback bridge passes integers and pointers only (src/arm64.c)", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__": main()
