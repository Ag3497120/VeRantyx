#!/usr/bin/env python3
"""Writes src/vk_dispatch_table.h: every Vulkan command the vk_*.m files define, with the Khronos names that are the
same command under an extension's suffix (vkTrimCommandPoolKHR is vkTrimCommandPool), and the level each is looked up
at (global, instance, device). `--check` fails when the file is out of date (make check runs it)."""
import re, sys, os, glob
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
src = os.path.join(root, 'src')
header = os.path.join(root, 'third_party', 'vulkan', 'vulkan', 'vulkan_core.h')
out = os.path.join(src, 'vk_dispatch_table.h')

defined = {}
for path in sorted(glob.glob(os.path.join(src, 'vk_*.m'))):
    text = open(path).read()
    for m in re.finditer(r'VKFN\s+[A-Za-z0-9_ *]+?\s+VKAPI_CALL\s+(vk[A-Za-z0-9]+)\s*\(\s*([A-Za-z0-9_]+)', text):
        defined[m.group(1)] = m.group(2)
official = set(re.findall(r'PFN_(vk[A-Za-z0-9]+)\)', open(header).read()))
GLOBAL = {'vkGetInstanceProcAddr', 'vkEnumerateInstanceVersion', 'vkEnumerateInstanceExtensionProperties',
          'vkEnumerateInstanceLayerProperties', 'vkCreateInstance'}
def level(name, first):
    if name in GLOBAL: return 0
    if first in ('VkInstance', 'VkPhysicalDevice'): return 1
    return 2
rows = []
for name in sorted(defined):
    lv = level(name, defined[name])
    rows.append((name, name, lv))
    for suffix in ('KHR', 'EXT'):
        alias = name + suffix
        if alias in official and alias not in defined: rows.append((alias, name, lv))
        # (and the core name of a command defined under an extension's suffix: vkCmdPushDescriptorSet)
        if name.endswith(suffix):
            core = name[:-len(suffix)]
            if core in official and core not in defined: rows.append((core, name, lv))
rows.sort()
text = ('// Generated by tools/vk_dispatch.py from the vk_*.m files: the Vulkan commands VXRuntime implements.\n'
        '// { name, function, level (0 global, 1 instance, 2 device) }\n')
for name, fn, lv in rows:
    text += '    { "%s", (PFN_vkVoidFunction)%s, %d },\n' % (name, fn, lv)
protos = '// Their declarations.\n'
if '--check' in sys.argv:
    cur = open(out).read() if os.path.exists(out) else ''
    if cur != text:
        print('src/vk_dispatch_table.h is out of date: run python3 tools/vk_dispatch.py'); sys.exit(1)
    print('vk_dispatch_table.h: %d commands -> ok' % len(rows))
else:
    open(out, 'w').write(text)
    print('%d commands (%d defined)' % (len(rows), len(defined)))
