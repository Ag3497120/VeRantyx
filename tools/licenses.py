#!/usr/bin/env python3
"""licenses.py: the license texts of everything the apps and the runtime kit carry, from one list.

  licenses.py write        (re)generate the Swift files the two apps show (LicensesText.swift in each)
  licenses.py check        exit 1 when those files are not what `write` would make (CI)
  licenses.py kit <dir>    the texts as files, for the runtime kit's LICENSES/ (engine/kit/build-kit.sh)

Each text is the component's own file: in the repository where the component lives here, else a copy in licenses/
(the components downloaded at build time, the menu font's own license record)."""
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# name in the kit, title shown, the text (a file under ROOT, or the text itself)
COMPONENTS = {
    "Glovebox": ("Glovebox", "LICENSE"),
    "Klepton": ("Klepton (Max Thomas)", "klepton/LICENSE"),
    "Apache-2.0": ("MoltenVK (The Khronos Group) and Steam Audio's default HRTF (Valve Corporation): "
                   "Apache License 2.0", "licenses/MoltenVK.txt"),
    "Fossilize": ("Fossilize (Valve Corporation)", "licenses/Fossilize.txt"),
    "LuaJIT": ("LuaJIT", "licenses/LuaJIT.txt"),
    "SDL3": ("SDL 3", "licenses/SDL3.txt"),
    "sdl2-compat": ("sdl2-compat", "licenses/sdl2-compat.txt"),
    "OpenVR": ("OpenVR SDK headers (Valve Corporation)", "klepton/runtime/openvr/third_party/openvr/LICENSE"),
    "SteamVR-Unity-Plugin": ("SteamVR Unity plugin hand-pose data (Valve Corporation)",
                             "klepton/runtime/openvr/third_party/steamvr_unity_plugin.LICENSE"),
    "GameNetworkingSockets": ("GameNetworkingSockets headers (Valve Corporation)",
                              "klepton/runtime/linux/steam/LICENSE-GameNetworkingSockets"),
    "zstd": ("Zstandard (Meta Platforms)", "launcher/Sources/CSteamSupport/zstd/LICENSE"),
    "LZMA-SDK": ("LZMA SDK decoder (Igor Pavlov)", "Public domain."),
    "DejaVu-Sans": ("DejaVu Sans (the in-game menu font)", "licenses/DejaVu-Sans.txt"),
    "Sparkle": ("Sparkle", "licenses/Sparkle.txt"),
}
HEADSET = ["Glovebox", "Klepton", "Apache-2.0", "Fossilize", "LuaJIT", "SDL3", "sdl2-compat", "OpenVR",
           "SteamVR-Unity-Plugin", "GameNetworkingSockets", "zstd", "LZMA-SDK", "DejaVu-Sans"]
# the installer carries the source and the runtime kit, so everything the headset app has, and Sparkle
INSTALLER = ["Glovebox", "Sparkle"] + HEADSET[1:]
SWIFT = {"launcher/App/AlyxLauncher/LicensesText.swift": HEADSET,
         "installer/App/Glovebox/LicensesText.swift": INSTALLER}


def text(name):
    _, src = COMPONENTS[name]
    p = os.path.join(ROOT, src)
    return open(p, encoding="utf-8").read().strip() if os.path.isfile(p) else src


def combined(names):
    return "\n\n\n".join(f"{COMPONENTS[n][0]}\n{'=' * len(COMPONENTS[n][0])}\n\n{text(n)}" for n in names)


def swift(names):
    body = combined(names)
    assert '"""#' not in body
    return ("// Generated by tools/licenses.py from the components' own license files; edit the list there.\n"
            "enum LicensesText {\n    static let all = #\"\"\"\n" + body + "\n\"\"\"#\n}\n")


def main(a):
    if a[:1] == ["write"]:
        for path, names in SWIFT.items():
            open(os.path.join(ROOT, path), "w", encoding="utf-8").write(swift(names))
            print(f"{path}: {len(names)} components")
        return 0
    if a[:1] == ["check"]:
        stale = [p for p, n in SWIFT.items()
                 if not os.path.exists(os.path.join(ROOT, p)) or open(os.path.join(ROOT, p), encoding="utf-8").read() != swift(n)]
        for p in stale:
            print(f"{p} is out of date: run tools/licenses.py write")
        return 1 if stale else 0
    if len(a) == 2 and a[0] == "kit":
        os.makedirs(a[1], exist_ok=True)
        for n in HEADSET:
            open(os.path.join(a[1], n + ".txt"), "w", encoding="utf-8").write(text(n) + "\n")
        shutil.copyfile(os.path.join(ROOT, "THIRD_PARTY_NOTICES.md"), os.path.join(a[1], "THIRD_PARTY_NOTICES.md"))
        return 0
    sys.exit(__doc__)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
