#!/usr/bin/env python3
"""vxrt agents: one source, every AI coding tool. The commands in .agents/commands/*.md, the vxrt MCP server in .mcp.json
and the rules in AGENTS.md are written out in the form each tool reads, so whichever one a user has (Claude Code,
Codex, Gemini CLI, Cursor) gets the same commands, the same tools and the same rules:

    Claude Code   CLAUDE.md (@AGENTS.md), .mcp.json, .claude/commands/*.md, .claude/skills -> .agents/skills
    Codex         AGENTS.md, .agents/skills, .codex/config.toml (MCP; Codex reads it once you trust the project)
    Gemini CLI    GEMINI.md (@AGENTS.md), .gemini/settings.json (MCP), .gemini/commands/*.toml
    Cursor        AGENTS.md, .cursor/rules/vxrt.mdc, .cursor/mcp.json, .cursor/commands/*.md

    tools/vxrt_agents.py sync     # write them (after changing a source)
    tools/vxrt_agents.py check    # are they up to date? (make -C VXRuntime check runs it)

A command source is Markdown with front matter (description, argument-hint); in its text {{args}} is what the user
typed after the command and {{agent}} the tool's name (tools/vxrt_doctor.py --agent words its brief for it).
"""
import json, os, re, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COMMANDS = os.path.join(REPO, ".agents", "commands")
MCP_TIMEOUT_S = 900                      # run_game takes minutes (a scenario plus SteamVR's start)
NOTE = "Generated by tools/vxrt_agents.py from {} — edit that, then run tools/vxrt_agents.py sync."

def commands():
    """[(name, front matter, text)] of .agents/commands/*.md."""
    out = []
    for f in sorted(os.listdir(COMMANDS)):
        if not f.endswith(".md"):
            continue
        m = re.match(r"---\n(.*?)\n---\n(.*)$", open(os.path.join(COMMANDS, f)).read(), re.S)
        if not m:
            sys.exit(f".agents/commands/{f}: needs front matter (---, description, argument-hint, ---)")
        meta = dict(line.split(": ", 1) for line in m.group(1).splitlines() if ": " in line)
        if "description" not in meta:
            sys.exit(f".agents/commands/{f}: no description")
        out.append((f[:-3], meta, m.group(2).strip() + "\n"))
    return out

def fill(text, args, agent):
    return text.replace("{{args}}", args).replace("{{agent}}", agent)

def mcp_server():
    """The vxrt server as .mcp.json registers it (command, args)."""
    s = json.load(open(os.path.join(REPO, ".mcp.json")))["mcpServers"]["vxrt"]
    return s["command"], s["args"]

def toml_str(s):
    return json.dumps(s, ensure_ascii=False)          # a JSON string is a valid TOML basic string

def outputs():
    """{path relative to the repository: content} of every generated file."""
    out = {}
    cmd, args = mcp_server()
    for name, meta, text in commands():
        src = f".agents/commands/{name}.md"
        hint = meta.get("argument-hint", "")
        # Claude Code: $ARGUMENTS is what follows /name.
        out[f".claude/commands/{name}.md"] = (
            f"---\ndescription: {meta['description']}\n" + (f"argument-hint: {hint}\n" if hint else "") + "---\n"
            f"<!-- {NOTE.format(src)} -->\n" + fill(text, "$ARGUMENTS", "claude"))
        # Gemini CLI: a TOML command, {{args}} is Gemini's own placeholder.
        out[f".gemini/commands/{name}.toml"] = (
            f"# {NOTE.format(src)}\ndescription = {toml_str(meta['description'])}\n"
            f"prompt = {toml_str(fill(text, '{{args}}', 'gemini'))}\n")
        # Cursor: the text the user types after the command follows the prompt.
        out[f".cursor/commands/{name}.md"] = (
            f"<!-- {NOTE.format(src)} -->\n" + fill(text, "<the game named after the command>", "cursor"))
    out[".gemini/settings.json"] = json.dumps({"mcpServers": {"vxrt": {"command": cmd, "args": args, "timeout": MCP_TIMEOUT_S * 1000}}}, indent=2) + "\n"
    out[".cursor/mcp.json"] = json.dumps({"mcpServers": {"vxrt": {"command": cmd, "args": args}}}, indent=2) + "\n"
    out[".codex/config.toml"] = (
        f"# {NOTE.format('.mcp.json')}\n# Codex reads a project's .codex/config.toml once you trust the project.\n"
        f"[mcp_servers.vxrt]\ncommand = {toml_str(cmd)}\nargs = [{', '.join(toml_str(a) for a in args)}]\n"
        f"tool_timeout_sec = {MCP_TIMEOUT_S}\n")
    out["GEMINI.md"] = f"<!-- {NOTE.format('AGENTS.md')} -->\n@./AGENTS.md\n"
    out[".cursor/rules/vxrt.mdc"] = (
        "---\ndescription: VeRantyx / VXRuntime rules for AI agents\nalwaysApply: true\n---\n"
        f"<!-- {NOTE.format('AGENTS.md')} -->\n"
        "Read AGENTS.md in the repository root before changing anything and follow it: its rules (no DRM or anti-cheat "
        "circumvention, game files untouched, verified work only), the build and test commands, and the harness "
        "(tools/vxrt_run.py, the vxrt MCP server in .cursor/mcp.json) for every claim about a game. Workflows: "
        ".agents/skills/*/SKILL.md. Commands: /vxrt-support, /vxrt-tune, /vxrt-games, /vxrt-issue.\n")
    return out

def stale():
    """Generated files whose content differs from what the sources give, and generated files no source makes now."""
    want = outputs()
    bad = [p for p, c in want.items() if not os.path.exists(os.path.join(REPO, p)) or open(os.path.join(REPO, p)).read() != c]
    for d, ext in ((".claude/commands", ".md"), (".gemini/commands", ".toml"), (".cursor/commands", ".md")):
        full = os.path.join(REPO, d)
        if os.path.isdir(full):
            bad += [f"{d}/{f} (no source)" for f in sorted(os.listdir(full)) if f.endswith(ext) and f"{d}/{f}" not in want]
    return bad

def main():
    if sys.argv[1:] == ["sync"]:
        for d in (".claude/commands", ".gemini/commands", ".cursor/commands"):   # (commands whose source is gone)
            full = os.path.join(REPO, d)
            for f in os.listdir(full) if os.path.isdir(full) else ():
                if f.startswith("vxrt-") and f"{d}/{f}" not in outputs():
                    os.remove(os.path.join(full, f))
        for p, c in outputs().items():
            os.makedirs(os.path.dirname(os.path.join(REPO, p)) or REPO, exist_ok=True)
            open(os.path.join(REPO, p), "w").write(c)
        print(f"agent files: {len(outputs())} written")
    elif sys.argv[1:] == ["check"]:
        bad = stale()
        for p in bad:
            print(f"{p}: out of date (tools/vxrt_agents.py sync)")
        print(f"agent files: {len(outputs())}, {len(bad)} out of date -> {'FAILED' if bad else 'ok'}")
        sys.exit(1 if bad else 0)
    else:
        sys.exit(__doc__)

if __name__ == "__main__":
    main()
